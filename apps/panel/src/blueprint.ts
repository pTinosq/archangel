/** Real things the owner says, walked through the flow a step at a time. */
export type Step = { at: string; say: string };
export type Scenario = { title: string; via: string; steps: Step[] };

const heard = (via: string, said: string, thread: Step[]): Step[] => [
  { at: "s_owner", say: `“${said}” arrives ${via}.` },
  { at: "gw", say: "The gateway turns it into an OwnerMessage and records the line." },
  ...thread,
  { at: "mark", say: "The thread is marked said in, so a summary already being written can't close it." },
  { at: "hear", say: "Meanwhile the twin's reader opens the pages that bear on it." },
  { at: "orch", say: "The orchestrator reads that thread's history, what the twin found, and the owner's style for this channel." },
  { at: "d_need", say: "It decides what this needs." },
];

const answered = (wrapped: boolean, call: boolean): Step[] => [
  { at: "reply", say: "It writes the reply." },
  { at: "d_wrap", say: wrapped ? "The router flagged a wrap-up." : "Nothing wrapped the thread up." },
  ...(wrapped
    ? [{ at: "close", say: "The thread closes once answered, and its summary is written in the background." }]
    : [{ at: "d_full", say: "The thread's context is well under 30k tokens, so it stays where it is." }]),
  { at: "out", say: "The gateway sends the reply to the channel it came from." },
  { at: "d_call", say: call ? "The owner is on a live call." : "It's not a call." },
  call ? { at: "speak", say: "It's spoken back to them." } : { at: "text", say: "It goes out as a text, or a line in the panel." },
];

const fromTask = (what: string): Step[] => [
  { at: "upd", say: what },
  { at: "s_task", say: "The TaskUpdate wakes the orchestrator." },
  { at: "t_task", say: "It's answered in the thread that started the task." },
  { at: "orch", say: "The orchestrator reads the update." },
];

